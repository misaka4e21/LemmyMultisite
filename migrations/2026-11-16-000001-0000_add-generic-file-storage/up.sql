ALTER TABLE local_site
    ADD COLUMN file_upload_disabled boolean NOT NULL DEFAULT false,
    ADD COLUMN file_max_upload_size_bytes bigint NOT NULL DEFAULT 26214400,
    ADD COLUMN file_allowed_mime_types text[] NOT NULL DEFAULT '{}';

CREATE TABLE file_object (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_hash text NOT NULL UNIQUE,
    storage_key text NOT NULL UNIQUE,
    size_bytes bigint NOT NULL,
    content_type text NOT NULL,
    published_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE file_reference (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id uuid NOT NULL UNIQUE,
    local_site_id integer NOT NULL REFERENCES local_site(id) ON UPDATE CASCADE ON DELETE CASCADE,
    file_id integer NOT NULL REFERENCES file_object(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    owner_person_id integer NOT NULL REFERENCES person(id) ON UPDATE CASCADE ON DELETE CASCADE,
    original_filename text NOT NULL,
    published_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_file_reference_file_id ON file_reference (file_id);
CREATE INDEX idx_file_reference_site_owner_published
    ON file_reference (local_site_id, owner_person_id, published_at DESC);
