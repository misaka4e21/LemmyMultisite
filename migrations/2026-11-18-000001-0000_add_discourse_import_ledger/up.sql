CREATE TABLE discourse_import_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_site_id integer NOT NULL REFERENCES local_site(id) ON DELETE CASCADE,
    source_fingerprint_sha256 text NOT NULL CHECK (source_fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
    source_version text NOT NULL,
    source_schema_version bigint NOT NULL,
    status text NOT NULL DEFAULT 'previewed' CHECK (status IN ('previewed', 'running', 'failed', 'completed')),
    report jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (local_site_id, source_fingerprint_sha256)
);

CREATE TABLE discourse_import_mapping (
    run_id bigint NOT NULL REFERENCES discourse_import_run(id) ON DELETE CASCADE,
    entity_type text NOT NULL,
    source_id text NOT NULL,
    target_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, entity_type, source_id),
    CHECK (target_id > 0)
);

CREATE TABLE discourse_import_phase (
    run_id bigint NOT NULL REFERENCES discourse_import_run(id) ON DELETE CASCADE,
    phase text NOT NULL,
    last_source_id text,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'running', 'failed', 'completed')),
    processed_count bigint NOT NULL DEFAULT 0 CHECK (processed_count >= 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, phase)
);
