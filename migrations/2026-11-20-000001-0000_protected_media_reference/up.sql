CREATE TABLE protected_media_reference (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_site_id integer NOT NULL REFERENCES local_site (id) ON UPDATE CASCADE ON DELETE CASCADE,
    file_reference_id integer REFERENCES file_reference (id) ON UPDATE CASCADE ON DELETE CASCADE,
    media_reference_id bigint REFERENCES media_reference (id) ON UPDATE CASCADE ON DELETE CASCADE,
    post_id integer REFERENCES post (id) ON UPDATE CASCADE ON DELETE CASCADE,
    private_message_id integer REFERENCES private_message (id) ON UPDATE CASCADE ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT protected_media_reference_one_blob_reference
        CHECK ((file_reference_id IS NOT NULL) <> (media_reference_id IS NOT NULL)),
    CONSTRAINT protected_media_reference_one_resource
        CHECK ((post_id IS NOT NULL) <> (private_message_id IS NOT NULL))
);

ALTER TABLE file_reference
    ADD COLUMN is_public boolean NOT NULL DEFAULT true;

CREATE UNIQUE INDEX idx_protected_file_reference_post
    ON protected_media_reference (file_reference_id, post_id)
    WHERE file_reference_id IS NOT NULL AND post_id IS NOT NULL;
CREATE UNIQUE INDEX idx_protected_file_reference_private_message
    ON protected_media_reference (file_reference_id, private_message_id)
    WHERE file_reference_id IS NOT NULL AND private_message_id IS NOT NULL;
CREATE UNIQUE INDEX idx_protected_media_reference_post
    ON protected_media_reference (media_reference_id, post_id)
    WHERE media_reference_id IS NOT NULL AND post_id IS NOT NULL;
CREATE UNIQUE INDEX idx_protected_media_reference_private_message
    ON protected_media_reference (media_reference_id, private_message_id)
    WHERE media_reference_id IS NOT NULL AND private_message_id IS NOT NULL;

CREATE INDEX idx_protected_media_reference_site
    ON protected_media_reference (local_site_id);
CREATE INDEX idx_protected_media_reference_post_id
    ON protected_media_reference (post_id)
    WHERE post_id IS NOT NULL;
CREATE INDEX idx_protected_media_reference_private_message_id
    ON protected_media_reference (private_message_id)
    WHERE private_message_id IS NOT NULL;
